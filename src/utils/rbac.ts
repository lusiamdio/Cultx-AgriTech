export const isViewAllowedForRole = (view: string, role: UserRole): boolean => {
  const config = ROLE_CONFIGS[role] || ROLE_CONFIGS.farmer;
  // landing, auth and consent are globally accessible
  if (view === "landing" || view === "consent" || view === "auth") return true;
  return config.allowedViews.includes(view);
};

export const getPrimaryViewForRole = (role: UserRole): string => {
  const config = ROLE_CONFIGS[role];
  return config ? config.primaryView : "dashboard";
};
